let lang = 'vi';
export const LANGS = Object.keys(dict);
export function detectLang() {
  return (navigator.language || 'vi').toLowerCase().startsWith('vi') ? 'vi' : 'en';
}
export function setLang(l) {
  lang = dict[l] ? l : 'vi';
  document.documentElement.lang = lang;
}
export const getLang = () => lang;

export function t(key, params = {}) {
  const s = dict[lang][key] ?? dict.vi[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? String(params[k]) : `{${k}}`));
}

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => (el.placeholder = t(el.dataset.i18nPlaceholder)));
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute('aria-label', el.title);
  });
  root.querySelectorAll('[data-i18n-label]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nLabel)));
}

// Chuyển mã lỗi của backend thành câu dễ hiểu.
export function errorText(err) {
  const map = {
    unauthorized: 'errUnauthorized',
    bad_credentials: 'errBadCredentials',
    too_many_attempts: 'errTooManyAttempts',
    router_unreachable: 'errRouterUnreachable',
    router_timeout: 'errRouterTimeout',
    model_not_found: 'errModelNotFound',
    quota_exhausted: 'errQuota',
    rate_limited: 'errRateLimited',
    provider_error: 'errProvider',
    router_auth: 'errRouterAuth',
    bad_request: 'errBadRequest',
    payload_too_large: 'errTooLarge',
    server_busy: 'errBusy',
    network: 'errNetwork',
    stream_interrupted: 'errStream',
    not_configured: 'errNotConfigured',
    origin_not_allowed: 'errOrigin',
    upstream_not_found: 'errNotFound',
    not_found: 'errNotFound',
  };
  const key = map[err?.code] || 'errUnknown';
  const sec = err?.retryAfter || 30;
  let text = t(key, { sec });
  if (err?.detail && ['provider_error', 'bad_request', 'router_auth', 'quota_exhausted', 'rate_limited', 'model_not_found'].includes(err.code)) {
    text += ' ' + t('errDetail', { detail: err.detail });
  }
  return text;
}
